import { test, expect } from '@playwright/test';
import { apiCall, registerAndLogin, seedAircraft } from './helpers';

test('H1/T1: Hobbs preference, exact total, saved readings and per-flight block override', async ({ page }) => {
  test.setTimeout(120_000);
  const auth = await registerAndLogin(page);
  await seedAircraft(page, auth.accessToken, { registration: 'N483HB', type: 'C172' });
  await page.goto('/profile');
  const preferenceSaved = page.waitForResponse((r) => r.request().method() === 'PATCH' && r.url().endsWith('/users/me'));
  await page.getByLabel('Default Flight Time Tracking Method').selectOption('hobbs');
  expect((await preferenceSaved).ok()).toBe(true);
  await expect(page.getByLabel('Default Flight Time Tracking Method')).toHaveValue('hobbs');
  await page.reload();
  await expect(page.getByLabel('Default Flight Time Tracking Method')).toHaveValue('hobbs');
  await page.goto('/flights');
  await page.getByRole('button', { name: 'Log Flight', exact: true }).click();
  await expect(page.getByLabel('Flight Time Tracking Method', { exact: true })).toHaveValue('hobbs');
  await page.locator('#aircraftReg').fill('N483HB');
  await page.locator('#departureIcao').fill('EDDF');
  await page.locator('#arrivalIcao').fill('EDDM');
  await page.getByLabel(/hobbs start/i).fill('1523.4');
  await page.getByLabel(/hobbs end/i).fill('1524.7');
  await expect(page.getByRole('status')).toContainText('1h 18m');
  await page.locator('button[type="submit"]').filter({ hasText: 'Log Flight' }).click();
  await expect(page.getByText('Log New Flight')).not.toBeVisible();
  const list = await apiCall(page, 'GET', '/flights', undefined, auth.accessToken);
  const flight = list.data.find((f: { aircraftReg: string }) => f.aircraftReg === 'N483HB');
  expect(flight).toMatchObject({ flightTimeMethod: 'hobbs', hobbsStartTenths: 15234, hobbsEndTenths: 15247, totalTime: 78 });
  await page.goto(`/flights/${flight.id}`);
  await expect(page.getByText('Hobbs Time', { exact: true })).toBeVisible();
  await page.goto('/profile');
  const blockSaved = page.waitForResponse((r) => r.request().method() === 'PATCH' && r.url().endsWith('/users/me'));
  await page.getByLabel('Default Flight Time Tracking Method').selectOption('block');
  expect((await blockSaved).ok()).toBe(true);
  await expect(page.getByLabel('Default Flight Time Tracking Method')).toHaveValue('block');
  const saved = await apiCall(page, 'GET', `/flights/${flight.id}`, undefined, auth.accessToken);
  expect(saved.totalTime).toBe(78);
  expect(saved.flightTimeMethod).toBe('hobbs');
  await page.goto('/flights');
  await page.getByRole('button', { name: 'Log Flight', exact: true }).click();
  await expect(page.getByLabel('Flight Time Tracking Method', { exact: true })).toHaveValue('block');
  await expect(page.getByLabel(/hobbs start/i)).not.toBeVisible();
});

test('decimal flight entry preserves independent PIC, dual and instrument minutes', async ({ page }) => {
  test.setTimeout(120_000);
  const auth=await registerAndLogin(page);
  await seedAircraft(page,auth.accessToken,{registration:'N483MC',type:'C172'});
  await apiCall(page,'PATCH','/users/me',{defaultFlightTimeMethod:'manual',timeDisplayFormat:'decimal',decimalSeparator:'dot'},auth.accessToken);
  await page.goto('/profile'); await page.reload();
  await expect(page.getByLabel('Default Flight Time Tracking Method')).toHaveValue('manual');
  await page.goto('/flights');
  await page.getByRole('button',{name:'Log Flight',exact:true}).click();
  await page.locator('#aircraftReg').fill('N483MC');
  await page.locator('#departureIcao').fill('KORD');await page.locator('#arrivalIcao').fill('KORD');
  await page.locator('#manualTotalTime').fill('invalid');
  await page.locator('#flightTimeMethod').selectOption('block');
  await expect(page.locator('#manualTotalTime')).not.toBeVisible();
  await page.locator('#flightTimeMethod').selectOption('manual');
  await page.locator('#manualTotalTime').fill('1.5');
  await page.locator('#picTime').fill('invalid');
  await expect(page.getByRole('alert')).toBeVisible();
  await page.getByRole('button',{name:'Reset to auto',exact:true}).click();
  await expect(page.locator('#picTime')).toHaveValue('');
  await expect(page.getByRole('alert')).not.toBeVisible();
  await page.locator('#picTime').fill('1.1');
  await page.locator('#dualTime').fill('1.5');
  await page.getByRole('button', { name:'Instrument / IFR', exact:true }).click();
  await page.locator('#simulatedInstrumentTime').fill('.5');
  await page.locator('button[type="submit"]').filter({hasText:'Log Flight'}).click();
  await expect(page.getByText('Log New Flight')).not.toBeVisible();
  const list=await apiCall(page,'GET','/flights',undefined,auth.accessToken);
  expect(list.data.find((f:{aircraftReg:string})=>f.aircraftReg==='N483MC')).toMatchObject({flightTimeMethod:'manual',manualTotalTime:90,totalTime:90,picTime:66,dualTime:90,simulatedInstrumentTime:30,picTimeOverride:true,dualTimeOverride:true});
});
